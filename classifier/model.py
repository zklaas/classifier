def is_open_licence(spdx: str) -> bool:
    s = (spdx or "").strip()
    if not s:
        return False
    # "A OR B" / "A AND B": every part must be open (an OR choice needs one).
    if " OR " in s:
        return any(is_open_licence(p) for p in s.split(" OR "))
    if " AND " in s:
        return all(is_open_licence(p) for p in s.split(" AND "))
    s = s.strip("() ")
    if s.endswith("+"):
        s = s[:-1] + "-or-later" if not s[:-1].endswith("-or-later") else s[:-1]
    return s in OPEN_LICENCES or s in {"GPL-2.0", "GPL-3.0", "LGPL-2.1", "LGPL-3.0",
                                        "AGPL-3.0"}


# --- registry --------------------------------------------------------------

def _default_settings() -> dict:
    return {
        "licensor": "",            # the licence creator, e.g. "Jane Doe"
        "aliases": [],             # other names/handles/emails that mean the licensor
        "ai_system": "Claude",
        "ai_maker": "Anthropic",
        "roots": [],               # folders that hold software folders (asked on first run)
        "github_owner": "",        # blank = the account gh is logged in as
        "default_licence": "MIT",
        "auto_private": True,      # make repos private without a second question
    }


def new_software(name: str, path: str) -> dict:
    return {
        "name": name,
        "path": path,
        "stage": "unset",
        "suite": "",
        "group_override": "",
        "attested": False,
        "attested_at": "",
        "licence": "",             # SPDX chosen for the software ('' = settings default)
        "notes": "",
        "repos": [],               # manual links [{"repo": "owner/name", "path": "sub/dir"}]
        "scan": None,              # last scan (see scanner.scan)
        "resolutions": {},         # finding key -> {"kind", "licence", "note", "by"}
        "claude_review": None,     # last imported claude-docker review
        "platforms": {},           # platform -> {"track": "", "note": ""}
        "platform_review": None,   # evidence / blockers from the last scan
        "public_summary": "",      # catalogue description ('' = README's first paragraph)
        "install_notes": "",       # extra catalogue text under the install steps
        "ai": {"level": "", "what": ""},   # licensor's AI-connection answer ('' = suggestion)
        "ai_review": None,         # what the scan found (aiuse.review)
    }


class Registry:
    def __init__(self, path: Path = REGISTRY):
        self.path = Path(path)
        self.settings = _default_settings()
        self.ignored: list[str] = []
        self.software: dict[str, dict] = {}
        self.load()

    def load(self):
        if not self.path.exists():
            return
        data = json.loads(self.path.read_text(encoding="utf-8"))
        self.settings.update(data.get("settings", {}))
        self.ignored = list(data.get("ignored", []))
        for name, sw in data.get("software", {}).items():
            full = new_software(name, sw.get("path", ""))
            full.update(sw)
            self.software[name] = full

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.path.with_suffix(".tmp")
        tmp.write_text(json.dumps({"version": 1, "settings": self.settings,
                                   "ignored": self.ignored,
                                   "software": self.software},
                                  indent=1, ensure_ascii=False), encoding="utf-8")
        tmp.replace(self.path)

    # -- discovery --
    def discover(self) -> list[str]:
        """Register every software folder under the roots not yet known.

        A folder counts as software when it holds code.  A git working tree
        that holds copies of two or more other software folders (a suite repo
        snapshot) is skipped, since it is a repository of
        other software, not software of its own.  Returns the names added.
        """
        added = []
        candidates = {}
        for root in self.settings["roots"]:
            r = Path(os.path.expanduser(root))
            if not r.is_dir():
                continue
            for d in sorted(r.iterdir()):
                if d.is_dir() and not d.name.startswith(".") and _has_code(d):
                    candidates[d.name] = d
        known_paths = {Path(s["path"]) for s in self.software.values()}
        names_lower = {n.lower() for n in candidates}
        for name, d in candidates.items():
            if name in self.ignored or d in known_paths or name in self.software:
                continue
            if (d / ".git").exists():
                subs = {c.name.lower() for c in d.iterdir() if c.is_dir()}
                if len(subs & (names_lower - {name.lower()})) >= 2:
                    continue
            self.software[name] = new_software(name, str(d))
            added.append(name)
        return added

    def add(self, path: str, name: str | None = None) -> str:
        p = Path(path).expanduser().resolve()
        name = name or p.name
        base, i = name, 2
        while name in self.software and Path(self.software[name]["path"]) != p:
            name, i = f"{base} ({i})", i + 1
        self.software.setdefault(name, new_software(name, str(p)))
        if name in self.ignored:
            self.ignored.remove(name)
        return name

    def ignore(self, name: str):
        self.software.pop(name, None)
        if name not in self.ignored:
            self.ignored.append(name)

    def owner_names(self) -> list[str]:
        out = [self.settings.get("licensor", "")] + list(self.settings.get("aliases", []))
        return [a.strip() for a in out if a and a.strip()]


CODE_EXT = {".py", ".js", ".mjs", ".ts", ".html", ".htm", ".css", ".sh", ".ps1",
            ".c", ".h", ".cpp", ".hpp", ".rs", ".go", ".java", ".lua", ".qml"}


def _has_code(d: Path, limit: int = 400) -> bool:
    n = 0
    for root, dirs, files in os.walk(d):
        dirs[:] = [x for x in dirs if not x.startswith(".") and x not in
                   {"__pycache__", "node_modules", "venv"}]
        for f in files:
            if Path(f).suffix.lower() in CODE_EXT:
                return True
            n += 1
            if n > limit:
                return False
    return False


# --- deriving status -------------------------------------------------------

def findings(sw: dict) -> list[dict]:
    """The last scan's findings plus any item a Claude review added that the
    scan had not listed (those must be resolved too)."""
    scan = list((sw.get("scan") or {}).get("findings", []))
    known = {f["key"] for f in scan}
    for it in (sw.get("claude_review") or {}).get("items", []):
        k = it.get("key", "")
        if k and k not in known:
            known.add(k)
            # "file:x.py", "asset:samples/*.wav", "vendored:lib/" -> the path or pattern
            path = k.split(":", 1)[1] if ":" in k else k
            path = path.split("#", 1)[0]            # "file:game.html#mulberry32" -> the file
            scan.append({"key": k, "kind": "claude", "title": "Claude found: " + path,
                         "detail": it.get("reason", ""), "paths": [path], "auto": None,
                         "count": 1})
    return scan


def unresolved(sw: dict) -> list[dict]:
    """Findings that still stand in the way of clearance."""
    res = sw.get("resolutions", {})
    out = []
    for f in findings(sw):
        r = res.get(f["key"]) or f.get("auto") or {}
        kind = r.get("kind", "")
        if kind not in OK_RESOLUTIONS:
            out.append(f)
        elif kind == "opensource" and not is_open_licence(r.get("licence", "")):
            out.append(f)
    return out


def resolution_of(sw: dict, finding: dict) -> dict:
    return sw.get("resolutions", {}).get(finding["key"]) or finding.get("auto") or {}


def clearance(sw: dict, current_fingerprint: str | None = None) -> tuple[bool, str]:
    """(cleared?, reason)."""
    scan = sw.get("scan")
    if not scan:
        return False, "Not scanned yet"
    if not Path(sw["path"]).is_dir():
        return False, "Folder is missing"
    if current_fingerprint is not None and current_fingerprint != scan.get("fingerprint"):
        return False, "Files changed since the last scan: rescan"
    left = unresolved(sw)
    if left:
        blocking = [f for f in left if resolution_of(sw, f).get("kind") == "restricted"]
        if blocking:
            return False, f"{len(blocking)} item(s) are not open-source"
        return False, f"{len(left)} provenance item(s) unresolved"
    if not sw.get("attested"):
        return False, "Provenance not yet confirmed by the licensor"
    return True, "Cleared"


def auto_group(stage: str, in_suite: bool, cleared: bool) -> str:
    if stage not in ("finished", "development"):
        return UNCLASSIFIED
    if in_suite:
        return RELEASABLE_SUITE if cleared else SUITE_PRIVATE
    if stage == "development":
        return DEV_PRIVATE
    return RELEASABLE if cleared else FINISHED_PRIVATE


def group(sw: dict, cleared: bool) -> tuple[str, str]:
    """(Development Group, note).  An override may move software to any group
    except a Releasable one when it is not Cleared."""
    auto = auto_group(sw.get("stage", "unset"), bool(sw.get("suite", "").strip()), cleared)
    ov = sw.get("group_override", "")
    if ov in GROUPS:
        if ov in RELEASABLE_GROUPS and not cleared:
            return auto, f"Chosen group '{ov}' needs clearance; using '{auto}'"
        if auto == UNCLASSIFIED and ov != DEV_PRIVATE:
            return ov, "Chosen by hand (stage not set)"
        return ov, "Chosen by hand"
    return auto, "From stage, suite and clearance"


def is_private(group_name: str) -> bool:
    return group_name in PRIVATE_GROUPS


def now() -> str:
    return time.strftime("%Y-%m-%d %H:%M")


def gh_path() -> str | None:
    import shutil
    for c in (shutil.which("gh"), str(Path.home() / ".local" / "bin" / "gh")):
        if c and Path(c).exists():
            return c
    return None


def gh_login() -> str:
    gh = gh_path()
    if not gh:
        return ""
    try:
        r = subprocess.run([gh, "api", "user", "--jq", ".login"], capture_output=True,
                           text=True, timeout=30)
        return r.stdout.strip() if r.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""
